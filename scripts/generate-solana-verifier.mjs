#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(import.meta.dirname, '..');
const manifestPath = path.join(root, 'protocol', 'setup', 'v2', 'manifest.json');
const transitionManifestPath = path.join(
  root,
  'protocol',
  'setup',
  'solana-transition-v1',
  'manifest.json',
);
const outputPath = path.join(
  root,
  'crates',
  'dagon-zkapi-solana',
  'src',
  'verifying_keys.rs',
);

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const transitionManifest = JSON.parse(
  fs.readFileSync(transitionManifestPath, 'utf8'),
);

function bytes(value) {
  const body = value.startsWith('0x') ? value.slice(2) : value;
  if (!/^[0-9a-f]{64}$/.test(body)) {
    throw new Error(`expected canonical 32-byte lowercase hex, got ${value}`);
  }
  return Array.from(Buffer.from(body, 'hex'));
}

function g1(point) {
  return [...bytes(point[0]), ...bytes(point[1])];
}

function g2(point) {
  // Solana alt_bn128 pairing uses c1,c0 for each Fq2 coordinate.
  return [
    ...bytes(point[0][1]),
    ...bytes(point[0][0]),
    ...bytes(point[1][1]),
    ...bytes(point[1][0]),
  ];
}

function array(values, indent = '    ') {
  const rows = [];
  for (let offset = 0; offset < values.length; offset += 16) {
    rows.push(`${indent}${values.slice(offset, offset + 16).join(', ')},`);
  }
  return `[
${rows.join('\n')}
${indent.slice(0, -4)}]`;
}

function key(name, value) {
  const ic = value.ic.map((point) => array(g1(point), '        ')).join(',\n        ');
  return `pub const ${name}: Groth16Verifyingkey<'static> = Groth16Verifyingkey {
    nr_pubinputs: ${value.ic.length},
    vk_alpha_g1: ${array(g1(value.alpha_g1), '        ')},
    vk_beta_g2: ${array(g2(value.beta_g2), '        ')},
    vk_gamme_g2: ${array(g2(value.gamma_g2), '        ')},
    vk_delta_g2: ${array(g2(value.delta_g2), '        ')},
    vk_ic: &[
        ${ic},
    ],
};`;
}

const source = `// @generated by scripts/generate-solana-verifier.mjs
// Source: protocol/setup/v2/manifest.json (${manifest.circuit_id})
// Source: protocol/setup/solana-transition-v1/manifest.json (${transitionManifest.circuit_id})
// Do not edit by hand.

use groth16_solana::groth16::Groth16Verifyingkey;

${key('REQUEST_VERIFYING_KEY', manifest.request)}

${key('WITHDRAWAL_VERIFYING_KEY', manifest.withdrawal)}

${key('TRANSITION_VERIFYING_KEY', transitionManifest.transition)}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== source) {
    console.error('Solana verifying-key constants are stale; run npm run generate:solana-vk');
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, source);
  console.log(`wrote ${path.relative(root, outputPath)}`);
}
