use ark_bn254::Fr;
use ark_crypto_primitives::sponge::poseidon::find_poseidon_ark_and_mds;
use ark_ff::PrimeField;

fn field(value: &Fr) -> String {
    let limbs = value.0 .0;
    format!(
        "Fr::new_unchecked(BigInt::new([{}, {}, {}, {}]))",
        limbs[0], limbs[1], limbs[2], limbs[3]
    )
}

fn matrix(name: &str, values: &[Vec<Fr>]) {
    println!("pub(super) const {name}: [[Fr; 3]; {}] = [", values.len());
    for row in values {
        println!(
            "    [{}, {}, {}],",
            field(&row[0]),
            field(&row[1]),
            field(&row[2])
        );
    }
    println!("];");
}

fn main() {
    let (ark, mds) = find_poseidon_ark_and_mds::<Fr>(Fr::MODULUS_BIT_SIZE as u64, 2, 8, 57, 0);
    println!("// @generated by `cargo run -p zkapi-core --example generate_poseidon_constants`.");
    println!("use ark_bn254::Fr;");
    println!("use ark_crypto_primitives::sponge::poseidon::PoseidonConfig;");
    println!("use ark_ff::BigInt;");
    println!();
    matrix("ARK", &ark);
    println!();
    matrix("MDS", &mds);
    println!();
    println!("pub(super) fn config() -> PoseidonConfig<Fr> {{");
    println!("    PoseidonConfig::new(");
    println!("        8, 57, 5,");
    println!("        MDS.iter().map(|row| row.to_vec()).collect(),");
    println!("        ARK.iter().map(|row| row.to_vec()).collect(),");
    println!("        2, 1,");
    println!("    )");
    println!("}}");
}
